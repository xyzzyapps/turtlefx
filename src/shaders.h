/* ---- 1. Unified 2D + Retro SDF Fragment Shader ---- */
static const char *FRAG_SCENE_2D =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D uPrims;\n"
"uniform int uPrimCount;\n"
"uniform vec2 uResolution;\n"
"uniform vec3 uClearColor;\n"
"uniform int uIsRetro;\n"
"\n"
"float sdSegment(vec2 p, vec2 a, vec2 b) {\n"
"    vec2 pa = p - a, ba = b - a;\n"
"    float denom = dot(ba, ba);\n"
"    float h = denom > 1e-6 ? clamp(dot(pa, ba) / denom, 0.0, 1.0) : 0.0;\n"
"    return length(pa - ba * h);\n"
"}\n"
"\n"
"float sdBox(vec2 p, vec2 b) {\n"
"    vec2 d = abs(p) - b;\n"
"    return length(max(d, 0.0)) + min(max(d.x, d.y), 0.0);\n"
"}\n"
"\n"
"float sdTriangle(vec2 p, vec2 p0, vec2 p1, vec2 p2) {\n"
"    vec2 e0 = p1 - p0, e1 = p2 - p1, e2 = p0 - p2;\n"
"    vec2 v0 = p - p0, v1 = p - p1, v2 = p - p2;\n"
"    vec2 pq0 = v0 - e0 * clamp(dot(v0, e0) / max(dot(e0, e0), 1e-6), 0.0, 1.0);\n"
"    vec2 pq1 = v1 - e1 * clamp(dot(v1, e1) / max(dot(e1, e1), 1e-6), 0.0, 1.0);\n"
"    vec2 pq2 = v2 - e2 * clamp(dot(v2, e2) / max(dot(e2, e2), 1e-6), 0.0, 1.0);\n"
"    float s = sign(e0.x * e2.y - e0.y * e2.x);\n"
"    vec2 d = min(min(\n"
"        vec2(dot(pq0, pq0), s * (v0.x * e0.y - v0.y * e0.x)),\n"
"        vec2(dot(pq1, pq1), s * (v1.x * e1.y - v1.y * e1.x))),\n"
"        vec2(dot(pq2, pq2), s * (v2.x * e2.y - v2.y * e2.x)));\n"
"    return -sqrt(d.x) * sign(d.y);\n"
"}\n"
"\n"
"void main() {\n"
"    vec2 p;\n"
"    if (uIsRetro == 1) {\n"
"        p = floor(fragTexCoord * uResolution) + 0.5;\n"
"    } else {\n"
"        p = vec2((fragTexCoord.x - 0.5) * uResolution.x,\n"
"                 (0.5 - fragTexCoord.y) * uResolution.y);\n"
"    }\n"
"\n"
"    vec3 col = uClearColor;\n"
"    float aa = (uIsRetro == 1) ? 0.45 : 1.0;\n"
"\n"
"    for (int i = 0; i < uPrimCount; i++) {\n"
"        vec4 t0 = texelFetch(uPrims, ivec2(i, 0), 0);\n"
"        vec4 t1 = texelFetch(uPrims, ivec2(i, 1), 0);\n"
"        vec4 t2 = texelFetch(uPrims, ivec2(i, 2), 0);\n"
"        vec4 t3 = texelFetch(uPrims, ivec2(i, 3), 0);\n"
"\n"
"        int type = int(t0.x + 0.5);\n"
"        float d = 1e6;\n"
"\n"
"        if (type == 1) { // SEGMENT\n"
"            d = sdSegment(p, vec2(t0.y, t0.z), vec2(t0.w, t1.x)) - t1.w;\n"
"        } else if (type == 2) { // CIRCLE / DOT\n"
"            d = length(p - vec2(t0.y, t0.z)) - t1.w;\n"
"        } else if (type == 3) { // ROTATED RECT\n"
"            vec2 q = p - vec2(t0.y, t0.z);\n"
"            float cs = cos(t1.w), sn = sin(t1.w);\n"
"            q = vec2(q.x * cs - q.y * sn, q.x * sn + q.y * cs);\n"
"            d = sdBox(q, vec2(t1.y, t1.z));\n"
"        } else if (type == 4) { // FILLED TRIANGLE\n"
"            d = sdTriangle(p, vec2(t0.y, t0.z), vec2(t0.w, t1.x), vec2(t1.y, t1.z));\n"
"        }\n"
"\n"
"        float cov = (uIsRetro == 1) ? step(d, 0.0) : (1.0 - smoothstep(-aa * 0.5, aa, d));\n"
"        float glowAmt = t3.x;\n"
"        float halo = 0.0;\n"
"        if (glowAmt > 0.01 && uIsRetro == 0) {\n"
"            float radius = 3.0 + glowAmt * 18.0;\n"
"            halo = exp(-max(d, 0.0) / radius) * glowAmt * 0.65;\n"
"        }\n"
"\n"
"        float alpha = clamp(cov * t2.a, 0.0, 1.0);\n"
"        int blendMode = int(t3.y + 0.5);\n"
"        if (blendMode == 1) {\n"
"            col += t2.rgb * (alpha + halo);\n"
"        } else {\n"
"            col = mix(col, t2.rgb, alpha);\n"
"            col += t2.rgb * halo;\n"
"        }\n"
"    }\n"
"\n"
"    finalColor = vec4(col, 1.0);\n"
"}\n";

/* ---- 2. 3D SDF Raymarching Fragment Shader ---- */
static const char *FRAG_SCENE_3D =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D uPrims;\n"
"uniform int uPrimCount;\n"
"uniform vec2 uResolution;\n"
"uniform vec3 uCamPos;\n"
"uniform vec3 uCamLook;\n"
"uniform float uCamFov;\n"
"uniform mat4 uViewProj;\n"
"uniform vec3 uSkyTop;\n"
"uniform vec3 uSkyBot;\n"
"uniform vec3 uLightDir;\n"
"uniform vec3 uLightColor;\n"
"uniform int uShadows;\n"
"uniform int uFogEnabled;\n"
"uniform vec3 uFogColor;\n"
"uniform float uFogNear;\n"
"uniform float uFogFar;\n"
"\n"
"float hash31(vec3 p) {\n"
"    p = fract(p * 0.1031);\n"
"    p += dot(p, p.yzx + 33.33);\n"
"    return fract((p.x + p.y) * p.z);\n"
"}\n"
"\n"
"float vnoise3(vec3 p) {\n"
"    vec3 i = floor(p);\n"
"    vec3 f = fract(p);\n"
"    f = f * f * (3.0 - 2.0 * f);\n"
"    float n000 = hash31(i + vec3(0,0,0));\n"
"    float n100 = hash31(i + vec3(1,0,0));\n"
"    float n010 = hash31(i + vec3(0,1,0));\n"
"    float n110 = hash31(i + vec3(1,1,0));\n"
"    float n001 = hash31(i + vec3(0,0,1));\n"
"    float n101 = hash31(i + vec3(1,0,1));\n"
"    float n011 = hash31(i + vec3(0,1,1));\n"
"    float n111 = hash31(i + vec3(1,1,1));\n"
"    return mix(\n"
"        mix(mix(n000, n100, f.x), mix(n010, n110, f.x), f.y),\n"
"        mix(mix(n001, n101, f.x), mix(n011, n111, f.x), f.y), f.z);\n"
"}\n"
"\n"
"float fbm3(vec3 p) {\n"
"    float v = 0.0;\n"
"    v += 0.55 * vnoise3(p);\n"
"    v += 0.30 * vnoise3(p * 2.13 + 7.1);\n"
"    v += 0.15 * vnoise3(p * 4.31 + 13.7);\n"
"    return v;\n"
"}\n"
"\n"
"float sdBox3(vec3 p, vec3 b) {\n"
"    vec3 q = abs(p) - b;\n"
"    return length(max(q, 0.0)) + min(max(q.x, max(q.y, q.z)), 0.0);\n"
"}\n"
"\n"
"float sdCylinderY(vec3 p, float r, float h) {\n"
"    vec2 d = abs(vec2(length(p.xz), p.y)) - vec2(r, h);\n"
"    return min(max(d.x, d.y), 0.0) + length(max(d, 0.0));\n"
"}\n"
"\n"
"float sdConeY(vec3 p, float r, float h) {\n"
"    // Upright cone: base at y = -h/2, tip at y = +h/2\n"
"    vec2 q = vec2(length(p.xz), p.y - h * 0.5);\n"
"    vec2 k1 = vec2(0.0, 0.0);\n"
"    vec2 k2 = vec2(r, -h);\n"
"    vec2 e = k2 - k1;\n"
"    vec2 ca = vec2(q.x - min(q.x, (q.y < -h) ? r : 0.0), abs(q.y + h * 0.5) - h * 0.5);\n"
"    vec2 cb = q - e * clamp(dot(q, e) / max(dot(e, e), 1e-6), 0.0, 1.0);\n"
"    float s = (cb.x < 0.0 && ca.y < 0.0) ? -1.0 : 1.0;\n"
"    return s * sqrt(min(dot(ca, ca), dot(cb, cb)));\n"
"}\n"
"\n"
"float sdTorusY(vec3 p, float majorR, float minorR) {\n"
"    vec2 q = vec2(length(p.xz) - majorR, p.y);\n"
"    return length(q) - minorR;\n"
"}\n"
"\n"
"float smin(float a, float b, float k, out float h) {\n"
"    h = clamp(0.5 + 0.5 * (b - a) / max(k, 1e-4), 0.0, 1.0);\n"
"    return mix(b, a, h) - k * h * (1.0 - h);\n"
"}\n"
"\n"
"struct Hit {\n"
"    float d;\n"
"    vec3 col;\n"
"    int mat;\n"
"    float param;\n"
"};\n"
"\n"
"Hit mapScene(vec3 p) {\n"
"    Hit res;\n"
"    res.d = 1e5;\n"
"    res.col = vec3(1.0);\n"
"    res.mat = 0;\n"
"    res.param = 0.0;\n"
"\n"
"    for (int i = 0; i < uPrimCount; i++) {\n"
"        vec4 r0 = texelFetch(uPrims, ivec2(i, 0), 0);\n"
"        vec4 r1 = texelFetch(uPrims, ivec2(i, 1), 0);\n"
"        vec4 r2 = texelFetch(uPrims, ivec2(i, 2), 0);\n"
"        vec4 r3 = texelFetch(uPrims, ivec2(i, 3), 0);\n"
"        vec4 r4 = texelFetch(uPrims, ivec2(i, 4), 0);\n"
"\n"
"        int type = int(r0.x + 0.5);\n"
"        vec3 pos = r0.yzw;\n"
"        vec3 fwd = r1.xyz;\n"
"        vec3 up  = r2.xyz;\n"
"        vec3 right = cross(up, fwd);\n"
"\n"
"        vec3 q = p - pos;\n"
"        float d = 1e5;\n"
"\n"
"        if (type == 1) { // SPHERE\n"
"            d = length(q) - r1.w;\n"
"        } else if (type == 2) { // CAPSULE along fwd from 0 to len\n"
"            float len = r1.w;\n"
"            float rad = r2.w;\n"
"            float h = clamp(dot(q, fwd), 0.0, len);\n"
"            d = length(q - fwd * h) - rad;\n"
"        } else {\n"
"            vec3 lp = vec3(dot(q, right), dot(q, up), dot(q, fwd));\n"
"            if (type == 3) { // BOX\n"
"                d = sdBox3(lp, vec3(r1.w, r2.w, r3.w));\n"
"            } else if (type == 4) { // CYLINDER\n"
"                d = sdCylinderY(lp, r1.w, r2.w);\n"
"            } else if (type == 5) { // CONE\n"
"                d = sdConeY(lp, r1.w, r2.w);\n"
"            } else if (type == 6) { // TORUS\n"
"                d = sdTorusY(lp, r1.w, r2.w);\n"
"            }\n"
"        }\n"
"\n"
"        int op = int(r4.w + 0.5);\n"
"        int mat = int(r4.x + 0.5);\n"
"        if (op == 2) { // CARVE (boolean subtraction)\n"
"            if (-d > res.d) {\n"
"                res.d = -d;\n"
"            }\n"
"        } else if (op == 1 && r4.z > 0.001 && res.d < 1e4) { // SMOOTH UNION\n"
"            float h;\n"
"            float sd = smin(res.d, d, r4.z, h);\n"
"            res.col = mix(r3.rgb, res.col, h);\n"
"            if (h < 0.5) { res.mat = mat; res.param = r4.y; }\n"
"            res.d = sd;\n"
"        } else { // HARD UNION\n"
"            if (d < res.d) {\n"
"                res.d = d;\n"
"                res.col = r3.rgb;\n"
"                res.mat = mat;\n"
"                res.param = r4.y;\n"
"            }\n"
"        }\n"
"    }\n"
"    return res;\n"
"}\n"
"\n"
"float mapDist(vec3 p) { return mapScene(p).d; }\n"
"\n"
"vec3 calcNormal(vec3 p) {\n"
"    const vec2 e = vec2(0.0025, -0.0025);\n"
"    return normalize(\n"
"        e.xyy * mapDist(p + e.xyy) +\n"
"        e.yyx * mapDist(p + e.yyx) +\n"
"        e.yxy * mapDist(p + e.yxy) +\n"
"        e.xxx * mapDist(p + e.xxx));\n"
"}\n"
"\n"
"float calcSoftShadow(vec3 ro, vec3 rd, float mint, float maxt, float k) {\n"
"    float res = 1.0;\n"
"    float t = mint;\n"
"    for (int i = 0; i < 28; i++) {\n"
"        float h = mapDist(ro + rd * t);\n"
"        if (h < 0.001) return 0.0;\n"
"        res = min(res, k * h / t);\n"
"        t += clamp(h, 0.04, 0.5);\n"
"        if (t > maxt) break;\n"
"    }\n"
"    return clamp(res, 0.0, 1.0);\n"
"}\n"
"\n"
"float calcAO(vec3 pos, vec3 nor) {\n"
"    float occ = 0.0, sca = 1.0;\n"
"    for (int i = 0; i < 4; i++) {\n"
"        float h = 0.05 + 0.14 * float(i);\n"
"        float d = mapDist(pos + h * nor);\n"
"        occ += (h - d) * sca;\n"
"        sca *= 0.7;\n"
"    }\n"
"    return clamp(1.0 - 2.2 * occ, 0.2, 1.0);\n"
"}\n"
"\n"
"void main() {\n"
"    vec2 ndc = vec2(fragTexCoord.x * 2.0 - 1.0, 1.0 - fragTexCoord.y * 2.0);\n"
"    ndc.x *= uResolution.x / max(uResolution.y, 1.0);\n"
"\n"
"    vec3 cw = normalize(uCamLook - uCamPos);\n"
"    vec3 cu = normalize(cross(cw, vec3(0.0, 1.0, 0.0)));\n"
"    vec3 cv = cross(cu, cw);\n"
"    float fl = 1.0 / tan(radians(uCamFov) * 0.5);\n"
"    vec3 rd = normalize(ndc.x * cu + ndc.y * cv + fl * cw);\n"
"\n"
"    vec3 sky = mix(uSkyTop, uSkyBot, clamp(fragTexCoord.y, 0.0, 1.0));\n"
"    vec3 col = sky;\n"
"\n"
"    float t = 0.0;\n"
"    bool hit = false;\n"
"    Hit h;\n"
"    for (int i = 0; i < 84; i++) {\n"
"        vec3 pos = uCamPos + rd * t;\n"
"        h = mapScene(pos);\n"
"        if (h.d < 0.0025) { hit = true; break; }\n"
"        t += h.d;\n"
"        if (t > 45.0) break;\n"
"    }\n"
"\n"
"    if (hit) {\n"
"        vec3 pos = uCamPos + rd * t;\n"
"        vec4 clipPos = uViewProj * vec4(pos, 1.0);\n"
"        gl_FragDepth = clamp((clipPos.z / clipPos.w) * 0.5 + 0.5, 0.0, 0.9999);\n"
"        if (h.mat == 2) { // EMISSIVE\n"
"            col = h.col * max(h.param, 1.0);\n"
"        } else {\n"
"            vec3 nor = calcNormal(pos);\n"
"            vec3 baseCol = h.col;\n"
"            if (h.mat == 3) { // WEATHERED GOTHIC STONE\n"
"                float n1 = fbm3(pos * 2.8);\n"
"                float n2 = vnoise3(pos * 9.5);\n"
"                vec3 bump = vec3(vnoise3(pos * 6.0 + vec3(1.7,0,0)) - 0.5,\n"
"                                 vnoise3(pos * 6.0 + vec3(0,3.1,0)) - 0.5,\n"
"                                 vnoise3(pos * 6.0 + vec3(0,0,5.3)) - 0.5);\n"
"                nor = normalize(nor + bump * (0.28 + h.param * 0.2));\n"
"                float crack = smoothstep(0.45, 0.52, abs(n1 - 0.5) * 2.0);\n"
"                baseCol *= (0.72 + 0.42 * n1) * (0.88 + 0.22 * n2) * mix(0.68, 1.0, crack);\n"
"            } else if (h.mat == 4) { // DUNGEON FLAGSTONE TILES\n"
"                float sz = max(h.param, 0.4);\n"
"                vec2 tp = pos.xz / sz;\n"
"                float row = floor(tp.y);\n"
"                tp.x += mod(row, 2.0) * 0.5;\n"
"                vec2 cell = floor(tp);\n"
"                vec2 f = fract(tp);\n"
"                float edgeDist = min(min(f.x, 1.0 - f.x), min(f.y, 1.0 - f.y));\n"
"                float grout = smoothstep(0.035, 0.09, edgeDist);\n"
"                float tileVar = 0.78 + 0.34 * hash31(vec3(cell, 11.3));\n"
"                float grit = fbm3(pos * 3.8);\n"
"                baseCol *= tileVar * (0.82 + 0.32 * grit) * mix(0.32, 1.0, grout);\n"
"                vec3 bump = vec3(vnoise3(pos * 7.5 + vec3(2.1,0,0)) - 0.5, 0.0,\n"
"                                 vnoise3(pos * 7.5 + vec3(0,0,4.7)) - 0.5);\n"
"                nor = normalize(nor + bump * 0.18);\n"
"            }\n"
"            vec3 ldir = normalize(-uLightDir);\n"
"            float diff = max(dot(nor, ldir), 0.0);\n"
"            float sh = (uShadows == 1 && diff > 0.01) ? calcSoftShadow(pos + nor * 0.02, ldir, 0.04, 16.0, 10.0) : 1.0;\n"
"            float ao = calcAO(pos, nor);\n"
"            vec3 hemi = mix(uSkyBot, uSkyTop, 0.5 + 0.5 * nor.y) * 0.45;\n"
"            vec3 rim = uSkyTop * pow(1.0 - max(dot(nor, -rd), 0.0), 3.0) * 0.35;\n"
"\n"
"            vec3 lit = baseCol * (uLightColor * diff * sh * 1.15 + hemi * ao) + rim * ao;\n"
"            if (h.mat == 1) { // GLOSSY\n"
"                vec3 halfV = normalize(ldir - rd);\n"
"                float rough = clamp(h.param, 0.05, 0.95);\n"
"                float spec = pow(max(dot(nor, halfV), 0.0), mix(96.0, 8.0, rough));\n"
"                lit += uLightColor * spec * sh * 0.75;\n"
"            }\n"
"            // Dynamic point-light bounce from emissive primitives (torches, crystals, slashes)\n"
"            for (int li = 0; li < uPrimCount; li++) {\n"
"                vec4 lr4 = texelFetch(uPrims, ivec2(li, 4), 0);\n"
"                if (int(lr4.x + 0.5) != 2) continue;\n"
"                vec4 lr0 = texelFetch(uPrims, ivec2(li, 0), 0);\n"
"                vec4 lr3 = texelFetch(uPrims, ivec2(li, 3), 0);\n"
"                vec3 toL = lr0.yzw - pos;\n"
"                float d2 = dot(toL, toL);\n"
"                if (d2 > 36.0) continue;\n"
"                float invD = inversesqrt(max(d2, 0.04));\n"
"                float ndl = max(dot(nor, toL * invD), 0.15);\n"
"                float atten = 1.0 / (1.0 + 0.50 * d2);\n"
"                lit += baseCol * lr3.rgb * (max(lr4.y, 1.0) * 0.20 * ndl * atten);\n"
"            }\n"
"            col = lit;\n"
"        }\n"
"\n"
"        if (uFogEnabled == 1) {\n"
"            float f = clamp((t - uFogNear) / max(uFogFar - uFogNear, 0.001), 0.0, 1.0);\n"
"            col = mix(col, uFogColor, f);\n"
"        }\n"
"    } else {\n"
"        gl_FragDepth = 0.99999;\n"
"        if (uFogEnabled == 1) {\n"
"            col = mix(sky, uFogColor, 0.65);\n"
"        }\n"
"    }\n"
"\n"
"    finalColor = vec4(col, 1.0);\n"
"}\n";

/* ---- 3. Bloom Bright-Pass Extraction Shader ---- */
static const char *FRAG_BLOOM_EXTRACT =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D texture0;\n"
"void main() {\n"
"    vec3 c = texture(texture0, fragTexCoord).rgb;\n"
"    float lum = dot(c, vec3(0.2126, 0.7152, 0.0722));\n"
"    float w = smoothstep(0.55, 1.05, lum);\n"
"    finalColor = vec4(c * w, 1.0);\n"
"}\n";

/* ---- 4. Separable 9-Tap Gaussian Blur Shader ---- */
static const char *FRAG_BLUR =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D texture0;\n"
"uniform vec2 uDir;\n"
"void main() {\n"
"    vec3 sum = texture(texture0, fragTexCoord).rgb * 0.227027;\n"
"    sum += texture(texture0, fragTexCoord + uDir * 1.3846).rgb * 0.316216;\n"
"    sum += texture(texture0, fragTexCoord - uDir * 1.3846).rgb * 0.316216;\n"
"    sum += texture(texture0, fragTexCoord + uDir * 3.2308).rgb * 0.070270;\n"
"    sum += texture(texture0, fragTexCoord - uDir * 3.2308).rgb * 0.070270;\n"
"    finalColor = vec4(sum, 1.0);\n"
"}\n";

/* ---- 5. Unified Post-FX Shader (Bloom + Retro Palette/Bayer Dither + CRT + Vignette) ---- */
static const char *FRAG_POST =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"out vec4 finalColor;\n"
"uniform sampler2D texture0;\n"
"uniform sampler2D uBloomTex;\n"
"uniform vec2 uOutRes;\n"
"uniform vec2 uRetroRes;\n"
"uniform int uBloomEnabled;\n"
"uniform float uBloomStrength;\n"
"uniform int uCrtEnabled;\n"
"uniform float uCrtScanlines;\n"
"uniform float uCrtCurve;\n"
"uniform float uVignette;\n"
"uniform int uPalette;\n"
"uniform int uDither;\n"
"\n"
"float bayer4(ivec2 p) {\n"
"    int x = p.x & 3;\n"
"    int y = p.y & 3;\n"
"    int idx = x + y * 4;\n"
"    const float m[16] = float[16](\n"
"         0.0,  8.0,  2.0, 10.0,\n"
"        12.0,  4.0, 14.0,  6.0,\n"
"         3.0, 11.0,  1.0,  9.0,\n"
"        15.0,  7.0, 13.0,  5.0\n"
"    );\n"
"    return (m[idx] / 16.0) - 0.5;\n"
"}\n"
"\n"
"vec3 quantizePico8(vec3 c) {\n"
"    const vec3 pal[16] = vec3[16](\n"
"        vec3(0.000,0.000,0.000), vec3(0.114,0.169,0.325), vec3(0.494,0.145,0.325), vec3(0.000,0.529,0.318),\n"
"        vec3(0.671,0.322,0.212), vec3(0.373,0.341,0.310), vec3(0.761,0.765,0.780), vec3(1.000,0.945,0.910),\n"
"        vec3(1.000,0.000,0.302), vec3(1.000,0.639,0.000), vec3(1.000,0.925,0.153), vec3(0.000,0.894,0.212),\n"
"        vec3(0.161,0.678,1.000), vec3(0.514,0.463,0.612), vec3(1.000,0.467,0.659), vec3(1.000,0.800,0.667)\n"
"    );\n"
"    vec3 best = pal[0];\n"
"    float bestD = 1e9;\n"
"    for (int i = 0; i < 16; i++) {\n"
"        vec3 diff = c - pal[i];\n"
"        float d = dot(diff, diff);\n"
"        if (d < bestD) { bestD = d; best = pal[i]; }\n"
"    }\n"
"    return best;\n"
"}\n"
"\n"
"vec3 quantizeGameboy(vec3 c) {\n"
"    float l = dot(c, vec3(0.299, 0.587, 0.114));\n"
"    if (l < 0.25) return vec3(0.059, 0.220, 0.059);\n"
"    if (l < 0.50) return vec3(0.188, 0.384, 0.188);\n"
"    if (l < 0.75) return vec3(0.545, 0.675, 0.059);\n"
"    return vec3(0.608, 0.737, 0.059);\n"
"}\n"
"\n"
"vec3 quantizeCGA(vec3 c) {\n"
"    const vec3 pal[4] = vec3[4](\n"
"        vec3(0.0, 0.0, 0.0), vec3(0.33, 1.0, 1.0),\n"
"        vec3(1.0, 0.33, 1.0), vec3(1.0, 1.0, 1.0)\n"
"    );\n"
"    vec3 best = pal[0]; float bestD = 1e9;\n"
"    for (int i = 0; i < 4; i++) {\n"
"        vec3 diff = c - pal[i]; float d = dot(diff, diff);\n"
"        if (d < bestD) { bestD = d; best = pal[i]; }\n"
"    }\n"
"    return best;\n"
"}\n"
"\n"
"vec3 quantizeSunset(vec3 c) {\n"
"    const vec3 pal[6] = vec3[6](\n"
"        vec3(0.09,0.06,0.16), vec3(0.28,0.11,0.34), vec3(0.64,0.16,0.38),\n"
"        vec3(0.92,0.36,0.29), vec3(0.99,0.68,0.32), vec3(1.00,0.95,0.74)\n"
"    );\n"
"    vec3 best = pal[0]; float bestD = 1e9;\n"
"    for (int i = 0; i < 6; i++) {\n"
"        vec3 diff = c - pal[i]; float d = dot(diff, diff);\n"
"        if (d < bestD) { bestD = d; best = pal[i]; }\n"
"    }\n"
"    return best;\n"
"}\n"
"\n"
"void main() {\n"
"    vec2 uv = fragTexCoord;\n"
"\n"
"    if (uCrtEnabled == 1 && uCrtCurve > 0.001) {\n"
"        vec2 cc = uv * 2.0 - 1.0;\n"
"        float r2 = dot(cc, cc);\n"
"        cc *= 1.0 + uCrtCurve * r2;\n"
"        uv = cc * 0.5 + 0.5;\n"
"        if (uv.x < 0.0 || uv.x > 1.0 || uv.y < 0.0 || uv.y > 1.0) {\n"
"            finalColor = vec4(0.01, 0.01, 0.015, 1.0);\n"
"            return;\n"
"        }\n"
"    }\n"
"\n"
"    vec3 col = texture(texture0, uv).rgb;\n"
"    if (uBloomEnabled == 1) {\n"
"        col += texture(uBloomTex, uv).rgb * uBloomStrength;\n"
"    }\n"
"\n"
"    // Soft ACES-like tone mapping before quantization\n"
"    col = col / (1.0 + col * 0.25);\n"
"\n"
"    if (uDither == 1) {\n"
"        ivec2 px = ivec2(uv * uRetroRes);\n"
"        col += bayer4(px) * 0.14;\n"
"    }\n"
"\n"
"    if (uPalette == 1)      col = quantizePico8(clamp(col, 0.0, 1.0));\n"
"    else if (uPalette == 2) col = quantizeGameboy(clamp(col, 0.0, 1.0));\n"
"    else if (uPalette == 3) col = quantizeCGA(clamp(col, 0.0, 1.0));\n"
"    else if (uPalette == 4) col = quantizeSunset(clamp(col, 0.0, 1.0));\n"
"\n"
"    if (uCrtEnabled == 1 && uCrtScanlines > 0.001) {\n"
"        float scan = sin(uv.y * uRetroRes.y * 3.14159265) * 0.5 + 0.5;\n"
"        col *= 1.0 - uCrtScanlines * (1.0 - scan * scan);\n"
"    }\n"
"\n"
"    if (uVignette > 0.001) {\n"
"        vec2 d = uv - 0.5;\n"
"        float vig = 1.0 - dot(d, d) * 2.4 * uVignette;\n"
"        col *= clamp(vig, 0.0, 1.0);\n"
"    }\n"
"\n"
"    finalColor = vec4(clamp(col, 0.0, 1.0), 1.0);\n"
"}\n";

